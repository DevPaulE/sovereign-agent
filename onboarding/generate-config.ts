#!/usr/bin/env bun
// generate-config.ts — turn onboarding answers into the person's config.
// Usage: bun onboarding/generate-config.ts answers.json [outDir]
//
// The answers are the onboarding chat's output. This writer never invents values;
// it only records the person's words into the four things they now own:
// the harness config, the context, the agent registry, and the answers themselves.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const [answersPath, outDir = "."] = process.argv.slice(2);
if (!answersPath) { console.error("usage: bun generate-config.ts answers.json [outDir]"); process.exit(1); }
const a = JSON.parse(readFileSync(answersPath, "utf8"));
mkdirSync(outDir, { recursive: true });

const config = {
  "$comment": "Generated by onboarding. Edit, then run harness/build.ts (or /lifeos-rebuild in pi), then /reload.",
  principal: a.name ?? "Principal",
  assistant: a.agentName ?? "Aria",
  paths: {
    skillsRoot: a.skillsRoot ?? "~/.claude/skills",
    personal: a.personalLayer ?? "~/.config/LIFEOS/USER",
    lifeos: a.lifeosDir ?? "~/.claude",
    toolbelt: a.toolbeltDir ?? "~/Projects/toolbelt",
    upstream: a.upstreamDir ?? "~/Reference/LifeOS-upstream",
  },
  skills: a.skills ?? {},
  model: { default: a.model ?? "openrouter/deepseek/deepseek-v4-pro" },
};

const self = {
  name: a.name, role: a.role ?? "",
  ideal: a.ideal ?? "", current: a.current ?? "",
  rails: a.rails ?? [], spine: a.spine ?? "",
  box: a.box ?? "", messenger: a.messenger ?? "",
  never: a.never ?? [], allowlist: a.allowlist ?? [],
  onboarded: new Date().toISOString(),
};

const registry = {
  default: "worker",
  agents: {
    worker: { kind: "pi", workspace: a.workspace ?? "~/agent/workspace", timeout_s: 300 },
    ...(a.peerHost ? { peer: { kind: "ssh", host: a.peerHost, timeout_s: 300 } } : {}),
  },
};

writeFileSync(join(outDir, "lifeos.config.json"), JSON.stringify(config, null, 2) + "\n");
writeFileSync(join(outDir, "SELF.json"), JSON.stringify(self, null, 2) + "\n");
writeFileSync(join(outDir, "registry.json"), JSON.stringify(registry, null, 2) + "\n");
console.log(`wrote lifeos.config.json, SELF.json, registry.json -> ${outDir}`);
console.log("next: paste the key values into .env (your hands), then install harness + daemon + sentinel.");
